  # 将文本转换为拼音
  # @param text [String] 原始文本
  # @return [String] 拼音格式的文本
  def self.convert(text)
    return text if text.nil? || text.empty?

    # 处理每个字符
    result = text.chars.map do |char|
      pin = PINYIN_TABLE[char]
      if pin
        pin
      elsif char.ascii_only?
        char
      else
        # 未收录的汉字使用hex编码
        char.codepoints.first.to_s(16)
      end
    end.join('_')

    # 清理多余的下划线
    result = result.gsub(/_+/, '_').gsub(/^_|_$/, '').downcase

    result
  end

  # 检查字符串是否包含非ASCII字符
  # @param text [String] 待检查文本
  # @return [Boolean] 是否包含非ASCII字符
  def self.needs_conversion?(text)
    !text.ascii_only?
  end
